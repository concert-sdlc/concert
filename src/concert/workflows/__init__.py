"""The workflow files Concert generates: deterministic text with a hash that can be pinned.

Only these renderers write Concert's workflows (never an agent), from the admin-merged
`process.yaml`. The runner later checks that the copy on each branch hashes to a pinned value, so
a hand edit or an upgrade in progress is visible. CI never runs on push, skips draft PRs, has
read-only permissions and no secrets; the watchdog runs on a schedule from the default branch.
"""

import hashlib
import re
from collections.abc import Mapping, Sequence
from importlib.metadata import PackageNotFoundError, version

CI_TEMPLATE = "concert-ci@1.0.0"
WATCHDOG_TEMPLATE = "concert-watchdog@1.0.0"
_NAME = re.compile(r"^[A-Za-z0-9_.-]+$")


def workflow_hash(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def render_ci(local: Mapping[str, str], setup: str | None = None) -> str:
    """One job per local check, named after it: the job name is the check name the PM reads."""
    if not local:
        raise ValueError("a CI workflow needs at least one check")
    for name in local:
        if not _NAME.match(name):
            raise ValueError(f"check name {name!r} must be letters, digits, '_', '.' or '-'")
    lines = [
        f"# Generated by Concert ({CI_TEMPLATE}). Do not edit: changes go through process.yaml.",
        "name: concert-ci",
        "on:",
        "  pull_request:",
        "    types: [ready_for_review, synchronize]",
        "  workflow_dispatch:",
        "permissions:",
        "  contents: read",
        "concurrency:",
        "  group: concert-ci-${{ github.event.pull_request.number || github.ref }}",
        "  cancel-in-progress: true",
        "jobs:",
    ]
    for name in sorted(local):
        lines += [
            f"  {name}:",
            "    if: github.event_name == 'workflow_dispatch' || github.event.pull_request.draft == false",
            "    runs-on: ubuntu-latest",
            "    steps:",
            "      - uses: actions/checkout@v4",
        ]
        for command in ([setup] if setup else []) + [local[name]]:
            lines += _run_step(command)
    return "\n".join(lines) + "\n"


def render_watchdog(
    every_hours: int,
    stale_minutes: int,
    steering: int,
    runners: Sequence[str],
    admins: Sequence[str],
    package_version: str | None = None,
) -> str:
    if not 1 <= every_hours <= 24:
        raise ValueError("every must be between 1 and 24 hours")
    for name in [*runners, *admins]:
        if not _NAME.match(name):
            raise ValueError(f"name {name!r} must be letters, digits, '_', '.' or '-'")
    pinned = package_version or _installed_version()
    command = (
        f"uvx --from concert-sdlc=={pinned} concert watchdog"
        " --repo ${{ github.repository }}"
        f" --steering {steering} --stale-after {stale_minutes}"
        f" --runners {','.join(runners)} --admins {','.join(admins)}"
    )
    lines = [
        f"# Generated by Concert ({WATCHDOG_TEMPLATE}). Do not edit: changes go through process.yaml.",
        "name: concert-watchdog",
        "on:",
        "  schedule:",
        f"    - cron: '0 */{every_hours} * * *'",
        "  workflow_dispatch:",
        "permissions:",
        "  contents: read",
        "  issues: write",
        "jobs:",
        "  watchdog:",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - uses: astral-sh/setup-uv@v5",
        "      - run: " + command,
        "        env:",
        "          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}",
    ]
    return "\n".join(lines) + "\n"


def _run_step(command: str) -> list[str]:
    cleaned = command.strip()
    if any(ord(c) < 0x20 and c not in "\n\t" for c in cleaned) or "\r" in cleaned:
        raise ValueError("a command must not contain control characters")
    return [
        "      - run: |-",
        *(f"          {line}" if line else "" for line in cleaned.split("\n")),
    ]


def _installed_version() -> str:
    try:
        return version("concert-sdlc")
    except PackageNotFoundError:  # running from a checkout that was never installed
        return "0.0.0"
